/* --------------------------------------------------------------------------
   2. HERO TYPING ANIMATION (Triggers when Hero is Scrolled Into View)
   -------------------------------------------------------------------------- */
function initHeroTypewriter() {
  const heroHerName = document.getElementById("hero-her-name");
  if (heroHerName) {
    heroHerName.textContent = CONFIG.heroTitle || `My ${CONFIG.herName}`;
  }

  const heroSection = document.getElementById("hero");
  if (heroSection) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            startHeroTyping();
            observer.disconnect();
          }
        });
      },
      { threshold: 0.25 }
    );
    observer.observe(heroSection);
  }
}

let typewriterStarted = false;
function startHeroTyping() {
  if (typewriterStarted) return;
  typewriterStarted = true;

  const targetEl = document.getElementById("hero-typing-text");
  if (!targetEl) return;

  const text = CONFIG.heroLoveMessage;
  let charIdx = 0;
  targetEl.innerHTML = "";

  function typeNextChar() {
    if (charIdx < text.length) {
      const char = text.charAt(charIdx);
      if (char === "\n") {
        targetEl.innerHTML += "<br>";
      } else {
        targetEl.innerHTML += char;
      }
      charIdx++;
      const delay = char === "." || char === "," ? 150 : 45;
      setTimeout(typeNextChar, delay);
    }
  }

  setTimeout(typeNextChar, 300);
}

/* --------------------------------------------------------------------------
   NAVIGATION (Clean fallback)
   -------------------------------------------------------------------------- */
function initNavigation() {
  // Seamless anchor scrolling for all in-page links
  document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
    anchor.addEventListener("click", function (e) {
      const targetId = this.getAttribute("href");
      if (targetId && targetId !== "#") {
        const targetElement = document.querySelector(targetId);
        if (targetElement) {
          e.preventDefault();
          targetElement.scrollIntoView({ behavior: "smooth" });
        }
      }
    });
  });
}

