let hugCount = 0;

function initFinalSurprise() {
  const line1 = document.getElementById("final-line-1");
  const line2 = document.getElementById("final-line-2");
  const line3 = document.getElementById("final-line-3");
  const hugBtn = document.getElementById("send-love-btn");
  const hugCountLabel = document.getElementById("hug-count");

  // Scroll observer to reveal lines sequentially
  const finalSection = document.getElementById("final-surprise");
  if (finalSection) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            setTimeout(() => line1 && line1.classList.add("visible"), 400);
            setTimeout(() => line2 && line2.classList.add("visible"), 1800);
            setTimeout(() => line3 && line3.classList.add("visible"), 3200);
            observer.disconnect();
          }
        });
      },
      { threshold: 0.3 }
    );
    observer.observe(finalSection);
  }

  // Interactive "Send a Warm Hug" Button
  if (hugBtn) {
    hugBtn.addEventListener("click", (e) => {
      hugCount++;
      if (hugCountLabel) hugCountLabel.textContent = hugCount;

      const rect = hugBtn.getBoundingClientRect();
      createHeartBurstAt(rect.left + rect.width / 2, rect.top + rect.height / 2, 22);

      // Sweet dynamic message on button
      if (hugCount === 1) {
        hugBtn.querySelector("span:first-child").textContent = "Hug Received with Love!";
      } else if (hugCount >= 5) {
        hugBtn.querySelector("span:first-child").textContent = "Shivam's Heart is Full!";
        triggerConfetti();
      }
    });
  }
}

/* --------------------------------------------------------------------------
   TAP / CLICK HEART BURSTS ANYWHERE
   -------------------------------------------------------------------------- */
function initGlobalTapHearts() {
  document.addEventListener("click", (e) => {
    // Avoid triggering on links or buttons to preserve normal UI feel
    if (e.target.closest("button") || e.target.closest("a") || e.target.closest("input")) {
      return;
    }
    createHeartBurstAt(e.clientX, e.clientY, 5);
  });
}

function createHeartBurstAt(x, y, count = 6) {
  const container = document.getElementById("floating-hearts-layer");
  if (!container) return;

  const emojis = ["❤️", "💖", "✨", "🌸", "💕"];
  for (let i = 0; i < count; i++) {
    const heart = document.createElement("span");
    heart.className = "tap-heart";
    heart.textContent = emojis[Math.floor(Math.random() * emojis.length)];

    // Slight random offset
    const offsetX = (Math.random() - 0.5) * 40;
    const offsetY = (Math.random() - 0.5) * 40;

    heart.style.left = `${x + offsetX}px`;
    heart.style.top = `${y + offsetY}px`;

    container.appendChild(heart);
    setTimeout(() => {
      heart.remove();
    }, 1200);
  }
}
