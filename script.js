function toggleMusic(audio, btn, icon, text) {
  if (!audio) return;

  if (audio.paused && !isSyntheticPlaying) {
    // Try playing user MP3 file first
    const playPromise = audio.play();
    if (playPromise !== undefined) {
      playPromise
        .then(() => {
          btn.classList.add("playing");
          icon.textContent = "⏸";
          text.textContent = "Pause Music";
        })
        .catch(() => {
          // If browser restricts or file missing, use gentle ambient synth
          startSyntheticRomanticMelody();
          btn.classList.add("playing");
          icon.textContent = "⏸";
          text.textContent = "Pause Music";
        });
    }
  } else {
    // Pause audio or synth
    if (!audio.paused) {
      audio.pause();
    }
    stopSyntheticRomanticMelody();
    btn.classList.remove("playing");
    icon.textContent = "▶";
    text.textContent = "Play Music";
  }
}

// Gentle Ambient Romantic Synth Melody for instant magic if our-song.mp3 is not yet placed
function startSyntheticRomanticMelody() {
  if (isSyntheticPlaying) return;
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    if (!audioCtx) audioCtx = new AudioContext();
    if (audioCtx.state === "suspended") audioCtx.resume();

    isSyntheticPlaying = true;
    const chords = [
      [261.63, 329.63, 392.0, 523.25], // C Maj
      [220.0, 261.63, 329.63, 440.0],  // A Min
      [174.61, 220.0, 261.63, 349.23], // F Maj
      [196.0, 246.94, 293.66, 392.0]   // G Maj
    ];
    let chordIndex = 0;

    function playNote(freq, timeOffset, duration) {
      if (!isSyntheticPlaying || !audioCtx) return;
      const osc = audioCtx.createOscillator();
      const gain = audioCtx.createGain();

      osc.type = "sine";
      osc.frequency.setValueAtTime(freq, audioCtx.currentTime + timeOffset);

      gain.gain.setValueAtTime(0.001, audioCtx.currentTime + timeOffset);
      gain.gain.exponentialRampToValueAtTime(0.05, audioCtx.currentTime + timeOffset + 0.15);
      gain.gain.exponentialRampToValueAtTime(0.0001, audioCtx.currentTime + timeOffset + duration);

      osc.connect(gain);
      gain.connect(audioCtx.destination);

      osc.start(audioCtx.currentTime + timeOffset);
      osc.stop(audioCtx.currentTime + timeOffset + duration + 0.2);
    }

    function triggerChord() {
      if (!isSyntheticPlaying) return;
      const current = chords[chordIndex % chords.length];
      current.forEach((note, idx) => {
        playNote(note, idx * 0.28, 2.5);
      });
      chordIndex++;
    }

    triggerChord();
    synthInterval = setInterval(triggerChord, 2600);
  } catch (e) {
    console.warn("Ambient audio error:", e);
  }
}

function stopSyntheticRomanticMelody() {
  isSyntheticPlaying = false;
  if (synthInterval) {
    clearInterval(synthInterval);
    synthInterval = null;
  }
}

